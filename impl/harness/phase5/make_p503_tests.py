"""Generates the P0.3 connector test files (Phase 5: EIP-8298 next to EIP-7851) from the Level 0 and Level 1 harness
files, reusing the P0.4 generator's patch points and helpers.

Usage: python -I make_p503_tests.py <fhe-authority-lifecycle dir>

EIP-8298 (Draft, SETCODEFROM) lets an EOA adopt regular deployed code; from then on EIP-3607 makes its ECDSA-signed
transactions invalid. No client implements it. The tests simulate the result on anvil: account X, a fresh local key,
gets the runtime code of a deployed `MLDSA44Account1271` (E4's ML-DSA-44 ERC-1271 wallet) with `anvil_setCode`. The
wallet keeps its whole state in immutables (verifier, key blob, key hash), so the code carries it and there is no
storage to copy. Calls into X then run the wallet against X's (empty) storage, as an adopted wallet would. Nothing
rewrites what a verifier reads: `eth_getCode(X)` returns the wallet's real regular code.

X retires through `anvil_impersonateAccount`, standing in for a call through its wallet code (this wallet has no
`execute`); the chain's own EIP-8298 behaviour (refusing the key's transactions) is not simulated here.

Outputs (each keeps its source file's tests, which are not run: the cargo filter is `p503_`):
  results/phase5/harness/main/crates/kms-worker/tests/acl_p503_eip8298.rs      unmodified worker, main
  results/phase5/harness/main-l1/crates/kms-worker/tests/acl_p503_eip8298_h.rs Level 1 worker (Profile H), main
  results/phase5/harness/v0.13.8/crates/kms-worker/tests/acl_p503_eip8298.rs   unmodified worker, v0.13.8
"""
