def renamed(text):
    """P0.4's helpers under Phase 5 names; the env variables keep their P04_ names (the run script sets them)."""
    text = text.replace("[Phase 4, P0.4] The EIP-7851 gap: helpers", "[Phase 5, P0.3] EIP-8298, simulated: helpers")
    text = text.replace("Env (set by run_p04.sh)", "Env (set by run_p503.sh)")
    for old, new in (("P04Mldsa", "P503Mldsa"),("P04Stack", "P503Stack"), ("P04-STACK", "P503-STACK"),
                     ("P04-RESULT", "P503-RESULT"), ("P04_F1600_CODEHASH", "P503_F1600_CODEHASH"),
                     ("P04_MLDSA_SEED_LABEL", "P503_MLDSA_SEED_LABEL"), ("fn p04_", "fn p503_"),
                     ("p04_log(", "p503_log("), ("p04_run()", "p503_run()"), ("p04_deploy_stack(", "p503_deploy_stack(")):
        text = text.replace(old, new)
    return text


COMMON_8298 = r'''
/// EIP-8298, simulated: `account` adopts the regular runtime code of `source` (anvil_setCode), read back from the node.
/// The source here keeps its state in immutables, so its code is the whole wallet; there is no storage to copy.
async fn p503_adopt_code(acl: &AnvilAcl, account: Address, source: Address) -> anyhow::Result<Bytes> {
    let code = acl.provider.get_code_at(source).await?;
    ensure!(!code.is_empty(), "source {source} has no code");
    ensure!(!(code.len() >= 2 && code[0] == 0xef && code[1] == 0x01), "source {source} has a delegation indicator");
    let _: serde_json::Value = acl.provider.raw_request("anvil_setCode".into(), (account, code.clone())).await?;
    ensure!(acl.provider.get_code_at(account).await? == code, "adopted code of {account} not in place");
    info!("P503-ADOPT account={account} source={source} code_len={} code_hash={}", code.len(), keccak256(&code));
    Ok(code)
}

/// X retires as itself: impersonated on anvil (standing in for a call through its wallet code), funded for gas.
async fn p503_retire_as_account(acl: &AnvilAcl, account: Address, case: &str) -> anyhow::Result<()> {
    let p = &acl.provider;
    let _: serde_json::Value = p
        .raw_request("anvil_setBalance".into(), (account, U256::from(1_000_000_000_000_000_000u128)))
        .await?;
    let _: serde_json::Value = p.raw_request("anvil_impersonateAccount".into(), (account,)).await?;
    let res = retire(acl, account, "x-8298", case).await;
    let _: serde_json::Value = p.raw_request("anvil_stopImpersonatingAccount".into(), (account,)).await?;
    res
}
'''

