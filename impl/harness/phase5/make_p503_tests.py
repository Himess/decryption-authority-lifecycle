def main():
    root = pathlib.Path(sys.argv[1])
    common = renamed(p04.COMMON_MAIN) + COMMON_8298
    jobs = [
        ("results/level0/harness/main/crates/kms-worker/tests/acl_retirement_real_chain.rs",
         "results/phase5/harness/main/crates/kms-worker/tests/acl_p503_eip8298.rs", "main", UNMODIFIED_MAIN),
        ("results/level1/harness/main/crates/kms-worker/tests/acl_profile_h_real_chain.rs",
         "results/phase5/harness/main-l1/crates/kms-worker/tests/acl_p503_eip8298_h.rs", "main", LEVEL1_MAIN),
        ("results/level0/harness/v0.13.8/crates/kms-worker/tests/acl_retirement_real_chain.rs",
         "results/phase5/harness/v0.13.8/crates/kms-worker/tests/acl_p503_eip8298.rs", "v0.13.8", V0138),
    ]
    for src, dst, line, section in jobs:
        text = (root / src).read_text(encoding="utf-8")
        if line == "main":
            text = p04.rep(text, p04.REQV2_FIELD_OLD, p04.REQV2_FIELD_NEW.replace("P04Mldsa", "P503Mldsa").replace(
                "[P0.4]", "[P0.3]"))
            text = p04.rep(text, p04.REQV2_INIT_OLD, p04.REQV2_INIT_NEW)
            text = p04.rep(text, p04.SIGN_OLD, p04.SIGN_NEW)
            section = common + section
        lines = text.splitlines(keepends=True)
        first_item = next(i for i, line_ in enumerate(lines) if not line_.startswith("//!"))
        text = HEADER + "".join(lines[:first_item]) + "#![allow(dead_code, unused_imports)]\n" + \
            "".join(lines[first_item:]) + section
        out = root / dst
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(root)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
