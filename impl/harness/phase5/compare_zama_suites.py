"""Compares runs of Zama's kms-worker suite (the lib and its eight test targets) on our trees (Phase 5).

Usage: python -I compare_zama_suites.py <out.md> <name>=<log> [<name>=<log> ...]

Each log is a heavy.sh log of `cargo test -p kms-worker --no-fail-fast ...`. A test is identified by its target (the
`Running ...` line that precedes it) and its name; its status is ok, FAILED or ignored. The report gives each run's
totals, the tests whose status differs between any two runs, and every failing test with the runs it failed in.
"""
import re
import sys

ANSI = re.compile(r"\x1b\[[0-9;]*m")
RUNNING = re.compile(r"^\s*Running (?:unittests )?(\S+)")
TEST = re.compile(r"^test (\S+) \.\.\. (ok|FAILED|ignored)$")
# A test whose own log output starts on its line: libtest prints the status alone on a later line.
PENDING = re.compile(r"^test (\S+) \.\.\. (?!ok$|FAILED$|ignored$)")
STATUS_ALONE = re.compile(r"^(ok|FAILED|ignored)$")
RESULT = re.compile(r"^test result: (\w+)\. (\d+) passed; (\d+) failed; (\d+) ignored")


def parse(path):
    tests, target, results, pending = {}, "?", [], None
    for line in open(path, encoding="utf-8", errors="replace"):
        line = ANSI.sub("", line.rstrip("\n"))
        m = RUNNING.match(line)
        if m:
            target = m.group(1).split("/")[-1] if "/" in m.group(1) else m.group(1)
            continue
        m = TEST.match(line)
        if m:
            tests[f"{target}::{m.group(1)}"] = m.group(2)
            pending = None
            continue
        m = PENDING.match(line)
        if m:
            pending = f"{target}::{m.group(1)}"
            continue
        m = STATUS_ALONE.match(line)
        if m and pending:
            tests[pending] = m.group(1)
            pending = None
            continue
        m = RESULT.match(line)
        if m:
            results.append((int(m.group(2)), int(m.group(3)), int(m.group(4))))
    return tests, results


def main():
    out = sys.argv[1]
    runs = [a.split("=", 1) for a in sys.argv[2:]]
    parsed = {name: parse(path) for name, path in runs}
    md = ["# Zama's kms-worker suite on our trees (Phase 5)", "",
          "Generated by `impl/harness/phase5/compare_zama_suites.py`. Docker is unreachable for the tests (D27), so the "
          "tests that start testcontainers fail the same way on every tree; a failure only on our tree would be ours.", "",
          "| Run | Log | Passed | Failed | Ignored | Tests seen |", "|---|---|---|---|---|---|"]
    for name, path in runs:
        tests, results = parsed[name]
        p = sum(r[0] for r in results); f = sum(r[1] for r in results); i = sum(r[2] for r in results)
        md.append(f"| {name} | `{path.split('results/')[-1]}` | {p} | {f} | {i} | {len(tests)} |")
    names = [n for n, _ in runs]
    all_tests = sorted(set().union(*(parsed[n][0].keys() for n in names)))
    differ = [t for t in all_tests if len({parsed[n][0].get(t, "absent") for n in names}) > 1]
    md += ["", f"## Tests whose status differs between runs: {len(differ)}", ""]
    if differ:
        md += ["| Test | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
        for t in differ:
            md.append(f"| `{t}` | " + " | ".join(parsed[n][0].get(t, "absent") for n in names) + " |")
    failing = [t for t in all_tests if any(parsed[n][0].get(t) == "FAILED" for n in names)]
    md += ["", f"## Failing tests: {len(failing)}", "", "| Test | Failed in |", "|---|---|"]
    for t in failing:
        md.append(f"| `{t}` | {', '.join(n for n in names if parsed[n][0].get(t) == 'FAILED')} |")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("\n".join(md[:8 + len(runs)]))
    print(f"differ={len(differ)} failing={len(failing)}")


if __name__ == "__main__":
    main()
