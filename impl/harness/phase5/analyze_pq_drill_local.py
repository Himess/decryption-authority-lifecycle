"""Builds the Part B local drill results (Phase 5) from the runs of run_pq_drill_local.sh.

Usage: python -I analyze_pq_drill_local.py <out.json> <out.md> <run_dir> [<run_dir> ...]

Each run directory holds PQL_result.json. Rows are grouped by hardfork (the run directory's prefix: osaka-*,
amsterdam-*) and keyed by kind and path. A row conforms when every run observed what the test expected. Receipts
(B8) are summarised per step: the gas used, as the set of values over the runs.
"""
import collections
import json
import pathlib
import re
import sys


def key_and_check(r):
    kind = r["kind"]
    if kind == "tx":
        return (kind, r["path"], r["action"]), r["observed"] == r["expected"] or (
            r["expected"] == "reverted" and str(r["observed"]).startswith("reverted")), f"{r['observed']} ({r.get('revert', '-')})"
    if kind == "sdk-status":
        exp, obs = r["expected"], r["observed"]
        ok = all(obs.get(k) == v for k, v in exp.items())
        return (kind, r["path"], r["who"]), ok, json.dumps(obs, sort_keys=True)
    if kind == "sdk-precheck":
        return (kind, r["path"], r["who"]), r["observed"]["accepted"] == r["expected"]["accepted"], json.dumps(r["observed"], sort_keys=True)
    if kind == "b5":
        return (kind, "-", r["what"]), r["observed"] == r["expected"], f"{r['observed']} ({r.get('revert', '-')}, gas {r.get('gasUsed')})"
    if kind == "canary":
        return (kind, "-", r["what"]), r["ok"] is True, "OK" if r["ok"] else "HALT"
    if kind == "undo":
        ok = r["delegatedToAttacker"] is False and r["pendingSuccessor"] == "0x0000000000000000000000000000000000000000"
        return (kind, r["path"], "holder undoes"), ok, json.dumps({k: r[k] for k in ("delegatedToAttacker", "pendingSuccessor")})
    if kind == "path":
        return (kind, r["path"], r["step"]), r.get("verified", True) is not False, json.dumps({k: v for k, v in r.items() if k not in ("kind", "path", "step")})
    if kind == "b8-erc1271":
        ok = r.get("returned") == "0x1626ba7e" and r.get("meterMagic", "0x1626ba7e") == "0x1626ba7e"
        return (kind, r["path"], "erc1271"), ok, json.dumps({k: r[k] for k in r if k not in ("kind", "path")}, sort_keys=True)
    return (kind, r.get("path", "-"), "-"), True, json.dumps(r)


def main():
    out_json, out_md, run_dirs = sys.argv[1], sys.argv[2], [pathlib.Path(p) for p in sys.argv[3:]]
    rows = collections.defaultdict(lambda: collections.OrderedDict())
    receipts = collections.defaultdict(lambda: collections.defaultdict(list))
    runs = collections.defaultdict(list)
    for d in run_dirs:
        hf = d.name.split("-")[0]
        res = json.loads((d / "PQL_result.json").read_text(encoding="utf-8"))
        runs[hf].append(d.name)
        for r in res["rows"]:
            k, ok, shown = key_and_check(r)
            rows[hf].setdefault(k, []).append({"run": d.name, "ok": ok, "shown": shown})
        for rc in res["receipts"]:
            what = re.sub(r"\b0x[0-9a-fA-F]{40}\b", "<addr>", str(rc.get("what")))
            receipts[hf][what].append({"run": d.name, "status": rc.get("status"), "gasUsed": rc.get("gasUsed")})
    report = {"runs": runs, "hardforks": {}}
    md = ["# Part B local drill (generated by impl/harness/phase5/analyze_pq_drill_local.py)", ""]
    for hf in sorted(rows):
        rr = []
        for (kind, path, what), obs in rows[hf].items():
            rr.append({"kind": kind, "path": path, "what": what, "runs": len(obs), "conforms": all(o["ok"] for o in obs),
                       "observed": sorted({o["shown"] for o in obs})})
        rec = []
        for what, obs in receipts[hf].items():
            rec.append({"step": what, "runs": len({o["run"] for o in obs}), "status": sorted({str(o["status"]) for o in obs}),
                        "gasUsed": sorted({str(o["gasUsed"]) for o in obs}, key=lambda x: int(x) if x.isdigit() else 0)})
        report["hardforks"][hf] = {"rows": rr, "receipts": rec,
                                   "summary": {"rows": len(rr), "conforming": sum(x["conforms"] for x in rr),
                                               "rows_all_runs": sum(x["runs"] == len(runs[hf]) for x in rr)}}
        s = report["hardforks"][hf]["summary"]
        md += [f"## {hf} ({len(runs[hf])} runs: {', '.join(runs[hf])})", "",
               f"Rows conforming: {s['conforming']}/{s['rows']} ({s['rows_all_runs']} seen in every run).", "",
               "| Kind | Path | What | Runs | Observed | OK |", "|---|---|---|---|---|---|"]
        for x in rr:
            md.append(f"| {x['kind']} | {x['path']} | {x['what']} | {x['runs']} | {' / '.join(x['observed'])[:220]} | {'yes' if x['conforms'] else '**NO**'} |")
        md += ["", f"### Receipts ({hf})", "", "| Step | Runs | Status | Gas used |", "|---|---|---|---|"]
        for x in rec:
            md.append(f"| {x['step']} | {x['runs']} | {','.join(x['status'])} | {', '.join(x['gasUsed'])} |")
        md.append("")
    pathlib.Path(out_json).write_text(json.dumps(report, indent=1), encoding="utf-8")
    pathlib.Path(out_md).write_text("\n".join(md) + "\n", encoding="utf-8")
    for hf, v in report["hardforks"].items():
        print(f"{hf}: {v['summary']['conforming']}/{v['summary']['rows']} rows conform over {len(runs[hf])} runs")


if __name__ == "__main__":
    main()
