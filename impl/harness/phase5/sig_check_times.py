"""Per-route wall time of the worker's signature check in the connector drill (Phase 5, B8 §3).

Usage: python -I sig_check_times.py <out.json> <out.md> <run_dir> [<run_dir> ...]

The Level 3 kms-worker logs one verdict per user-decryption request it checks, with `sig_check_us`: the time from the
start of its signature check to the verdict. That span includes the Postgres read of the attempt counter, the RPC reads
of the account's code and registry state, the ERC-1271 `eth_call` (route Erc1271) or both native ML-DSA verifications
(E3's K8), so it is the check's latency on the VPS, not the bare cryptography. The VPS runs everything under
heavy.sh's limits (two CPUs at nice 19), with anvil and a recording proxy on the same host.
"""
import json
import pathlib
import re
import statistics
import sys

ANSI = re.compile(r"\x1b\[[0-9;]*m")
H = re.compile(r"PROFILE-H accepted signer=\S+ path=(?P<path>\w+) .* sig_check_us=(?P<us>\d+)")
E3 = re.compile(r"E3 KDA (?P<verdict>accepted|rejected) signer=\S+ .*sig_check_us=(?P<us>\d+)")


def pct(xs, p):
    xs = sorted(xs)
    k = max(0, min(len(xs) - 1, round(p / 100 * (len(xs) - 1))))
    return xs[k]


def main():
    out_json, out_md, runs = sys.argv[1], sys.argv[2], [pathlib.Path(r) for r in sys.argv[3:]]
    per = {}
    for run in runs:
        for line in (run / "test.log").read_text(encoding="utf-8", errors="replace").splitlines():
            line = ANSI.sub("", line)
            m = H.search(line)
            if m:
                key = {"Erc1271": "ERC-1271 (Profile H, accepted)", "Ecrecover": "ecrecover (Profile H, accepted)"}.get(
                    m["path"], m["path"])
                per.setdefault(key, {}).setdefault(run.name, []).append(int(m["us"]))
                continue
            m = E3.search(line)
            if m:
                key = f"E3 KDA, ML-DSA-44 with K8 ({m['verdict']})"
                per.setdefault(key, {}).setdefault(run.name, []).append(int(m["us"]))
    rows = []
    for route, by_run in sorted(per.items()):
        allv = [v for vs in by_run.values() for v in vs]
        rows.append({
            "route": route,
            "count_per_run": {r: len(v) for r, v in by_run.items()},
            "median_ms": round(statistics.median(allv) / 1000, 1),
            "p10_ms": round(pct(allv, 10) / 1000, 1),
            "p90_ms": round(pct(allv, 90) / 1000, 1),
            "min_ms": round(min(allv) / 1000, 1),
            "max_ms": round(max(allv) / 1000, 1),
            "median_ms_per_run": {r: round(statistics.median(v) / 1000, 1) for r, v in by_run.items()},
        })
    json.dump({"runs": [r.name for r in runs], "routes": rows}, open(out_json, "w", encoding="utf-8"), indent=1)
    md = ["# Worker signature-check time per route (connector drill, VPS)", "",
          f"Generated by `impl/harness/phase5/sig_check_times.py` from {len(runs)} runs ({', '.join(r.name for r in runs)}).",
          "`sig_check_us` spans the whole check: the attempt counter's Postgres read, the RPC reads, and the ERC-1271 "
          "`eth_call` or E3's two native verifications. Everything ran on the VPS under heavy.sh's limits, with every "
          "RPC through the recording proxy. So this is harness time, as Phase 4 P1.1 noted for the same log line: it "
          "compares the routes inside one set-up, and is not a latency figure. Latencies and native verification "
          "times are Phase 4 P1.1's bench (`results/phase4/P1_1_E3_CONNECTOR.md` §8).", "",
          "| Route | Checks per run | Median (ms) | p10–p90 (ms) | Min–max (ms) | Median per run (ms) |",
          "|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['route']} | {', '.join(str(c) for c in r['count_per_run'].values())} | {r['median_ms']} | "
                  f"{r['p10_ms']}–{r['p90_ms']} | {r['min_ms']}–{r['max_ms']} | "
                  f"{', '.join(str(v) for v in r['median_ms_per_run'].values())} |")
    open(out_md, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
