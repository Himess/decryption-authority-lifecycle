"""Compares the clean re-runs of the unmodified-tree connector evidence with the committed runs (Phase 5, P3; D120).

Usage: python -I compare_recheck.py <out.md> <family>=<committed run dir glob>|<re-run dir glob> ...

Each run directory holds test.log, whose result lines have the form `<KIND>-RESULT ... key=value ...`. A row is named
by its `label` (its run id, `.r1.`, `.rc1.` and the like, removed) or, where a test logs no label, by its `step`.
Per row and per side (all runs of that side), the script collects the values of each field.
- The outcome fields (`expected`, `observed`; for the stored-result test `http_status`, `expected_status`,
  `expected_code`, `request_row`) must have one value on each side, and the same one: else the row differs.
- The other fields (`error_code`, `error_counter`, `status`, `kms_mock_hits`, `kms_mock_hits_delta`, `already_sent`)
  vary between runs for some rows (a fault's timing decides which error is logged and how often the KMS mock is hit);
  a re-run value never seen in the committed runs is listed.
"""
import glob
import re
import sys

LINE = re.compile(r"\b([A-Z0-9]+)-RESULT\s+(.*)$")
PAIR = re.compile(r'(\w+)=("[^"]*"|\S+)')
RUN_ID = re.compile(r"\.(?:r|rc)\d+(?=\.|$)")
OUTCOME = ("expected", "observed", "http_status", "expected_status", "expected_code", "request_row")
OTHER = ("error_code", "error_counter", "status", "kms_mock_hits", "kms_mock_hits_delta", "already_sent")
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def rows(pattern):
    """{(kind, name): {field: set(values)}}, and the number of runs read."""
    out, runs = {}, 0
    for d in sorted(glob.glob(pattern)):
        runs += 1
        for line in open(f"{d}/test.log", encoding="utf-8", errors="replace"):
            m = LINE.search(ANSI.sub("", line))
            if not m:
                continue
            kv = {k: v.strip('"') for k, v in PAIR.findall(m.group(2))}
            name = RUN_ID.sub("", kv["label"]) if "label" in kv else kv.get("step")
            if name is None:
                continue
            entry = out.setdefault((m.group(1), name), {f: set() for f in OUTCOME + OTHER})
            for f in OUTCOME + OTHER:
                if f in kv:
                    entry[f].add(kv[f])
    return out, runs


def main():
    out_md = sys.argv[1]
    md = ["# Clean re-runs of the unmodified-tree connector evidence, compared with the committed runs", "",
          "Generated by `impl/harness/phase5/compare_recheck.py` (D120). A row agrees when its outcome fields have one",
          "and the same value in every committed run and every re-run.", "",
          "| Family | Committed runs | Re-runs | Rows | Outcomes agree | Outcomes differ | One side only | Other fields: new values |",
          "|---|---|---|---|---|---|---|---|"]
    details, notes, bad = [], [], 0
    for arg in sys.argv[2:]:
        family, globs = arg.split("=", 1)
        committed_glob, rerun_glob = globs.split("|", 1)
        a, na = rows(committed_glob)
        b, nb = rows(rerun_glob)
        keys = sorted(set(a) | set(b))
        agree = differ = one = new = 0
        for k in keys:
            if k not in a or k not in b:
                one += 1
                details.append(f"- {family} `{k[0]} {k[1]}`: only in the {'committed runs' if k in a else 're-runs'}")
                continue
            if all(len(a[k][f]) <= 1 and a[k][f] == b[k][f] for f in OUTCOME):
                agree += 1
            else:
                differ += 1
                details.append(f"- {family} `{k[0]} {k[1]}`: " + "; ".join(
                    f"{f} {sorted(a[k][f])} vs {sorted(b[k][f])}" for f in OUTCOME if a[k][f] != b[k][f] or len(a[k][f]) > 1))
            extra = [f"{f} {sorted(b[k][f] - a[k][f])} (committed: {sorted(a[k][f])})" for f in OTHER if b[k][f] - a[k][f]]
            if extra:
                new += 1
                notes.append(f"- {family} `{k[0]} {k[1]}`: " + "; ".join(extra))
        bad += differ + one
        md.append(f"| {family} | {na} | {nb} | {len(keys)} | {agree} | {differ} | {one} | {new} |")
    md += ["", f"Rows whose outcome differs, or that appear on one side only: {bad}."]
    if details:
        md += ["", "## Rows whose outcome differs", ""] + details
    if notes:
        md += ["", "## Other fields with a value the committed runs never logged", ""] + notes
    open(out_md, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("\n".join(md[5:5 + 2 + len(sys.argv) - 2]))
    print(md[-1] if not details and not notes else f"{bad} outcome differences; {len(notes)} rows with new values")


if __name__ == "__main__":
    main()
