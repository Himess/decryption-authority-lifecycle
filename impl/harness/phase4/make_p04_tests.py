def rep(text, old, new, count=1):
    n = text.count(old)
    assert n == count, (old[:60], n)
    return text.replace(old, new)


def with_header(text, allow):
    lines = text.splitlines(keepends=True)
    first_item = next(i for i, line in enumerate(lines) if not line.startswith("//!"))
    return HEADER + "".join(lines[:first_item]) + allow + "".join(lines[first_item:])


