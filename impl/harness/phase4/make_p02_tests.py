"""Generates the P0.2 (TC14) connector test files from the Level 0 harness files.

Usage: python -I make_p02_tests.py <fhe-authority-lifecycle dir>

TC14 measures when a retirement starts to bind the UNMODIFIED kms-worker. The worker reads every ACL view at
"latest" (no block is pinned), so its decision block is the host node's head when each view call is evaluated.
Four cases, on both lines, each with its own subject (an anvil account granted the test handle):

  after    the subject is retired at block N; a request picked up after N is refused;
  race     the request's isAllowed call is evaluated before N and its answer held by the proxy (`hold`) while the
           subject is retired at N; the worker then receives the pre-N answer and forwards the request;
  reorg    retired at N, a request is refused; anvil_rollback(1) removes block N; the next request is forwarded;
  restart  (a) worker A picks the request and is stopped during its held isAllowed call; the row is unlocked as the
           tx-sender's recovery routine does (`under_process` -> `pending`); the subject is retired; worker B
           re-runs the check and refuses. (b) a row marked `already_sent` (a worker sent it to the KMS and
           stopped): forwarded by polling when the subject is not retired; refused, with no poll, once retired.

Outputs (the Level 0 tests stay in the file and are not run; the cargo filter is `p02_`):
  results/phase4/harness/main/crates/kms-worker/tests/acl_p02_decision_lag.rs
  results/phase4/harness/v0.13.8/crates/kms-worker/tests/acl_p02_decision_lag.rs
"""
