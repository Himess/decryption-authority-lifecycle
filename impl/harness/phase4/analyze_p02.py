"""Builds the TC14 table (Phase 4, P0.2) from the runs of run_p02.sh.

Usage: python -I analyze_p02.py <out.json> <out.md> <run_dir> [<run_dir> ...]

Each run directory holds test.log (P02-RESULT lines) and host_rpc.jsonl (fault_proxy_v2 with --heads: every
forwarded eth_call carries the node's head block). For every case it reports, per run: expected and observed
outcome, KMS-mock hits, attempts, the head blocks at which the request's isAllowed calls were evaluated, and the
retirement block; for the race, the times from evaluation to retirement and to the worker's forward.
"""
import collections
import json
import pathlib
import re
import sys

RESULT = re.compile(
    r"P02-RESULT label=(?P<label>\S+) version=(?P<version>\S+) case=(?P<case>\S+) expected=(?P<expected>\S+) "
    r"observed=(?P<observed>\S+) kms_mock_hits=(?P<kms>\S+) error_counter=(?P<ec>\S+) status=(?P<status>\S+)(?P<extra>.*)$"
)
IS_ALLOWED = "0x82027b6d"


def kv(extra):
    return dict(m.groups() for m in re.finditer(r"(\w+)=(\S+)", extra))


def heads_by_label(path):
    out = collections.defaultdict(list)
    for line in open(path, encoding="utf-8"):
        r = json.loads(line)
        req = r["req"]
        if req.get("method") != "eth_call":
            continue
        data = (req["params"][0].get("input") or req["params"][0].get("data") or "")[:10].lower()
        if data != IS_ALLOWED:
            continue
        resp = r.get("resp")
        value = resp.get("result") if isinstance(resp, dict) else None
        out[r["path"].strip("/")].append({
            "head": r.get("head"), "fault": r.get("fault"), "aborted": bool(r.get("aborted")),
            "answer": (value[-1:] if value else None), "t0": r["t0"], "t": r["t"],
        })
    return out


def main():
    out_json, out_md = sys.argv[1], sys.argv[2]
    rows = collections.OrderedDict()
    for run_dir in map(pathlib.Path, sys.argv[3:]):
        text = (run_dir / "test.log").read_text(encoding="utf-8", errors="replace")
        wire = heads_by_label(run_dir / "host_rpc.jsonl")
        for line in text.splitlines():
            m = RESULT.search(line)
            if not m:
                continue
            d = m.groupdict()
            extra = kv(d["extra"])
            calls = wire.get(d["label"], [])
            run = d["label"].split(".")[1]
            obs = {
                "run": run, "expected": d["expected"], "observed": d["observed"], "kms_hits": d["kms"],
                "attempts": d["ec"], "status": d["status"], "extra": extra,
                "isAllowed_heads": sorted({c["head"] for c in calls if c["head"] is not None}),
                "isAllowed_calls": len(calls),
            }
            if d["case"] == "race" and "t_eval" in extra:
                t_eval, t_ret, t_out = float(extra["t_eval"]), float(extra["t_retired"]), float(extra["t_outcome_seen"])
                obs["race_ms"] = {"eval_to_retired": round((t_ret - t_eval) * 1000), "eval_to_outcome_seen": round((t_out - t_eval) * 1000)}
            rows.setdefault((d["version"], d["case"]), []).append(obs)
    report = []
    md = ["# TC14 table (generated by impl/harness/phase4/analyze_p02.py)", "",
          "| Line | Case | Runs | Expected | Observed | KMS hits | Attempts | isAllowed evaluated at head | Retirement block | Notes | OK |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for (version, case), obs in rows.items():
        ok = all(o["observed"] == o["expected"] for o in obs)
        heads = sorted({h for o in obs for h in o["isAllowed_heads"]})
        retire = sorted({o["extra"].get("retire_block") or o["extra"].get("rolled_back_block") or "-" for o in obs})
        notes = []
        if case == "race":
            ev = sorted({o["extra"].get("eval_head") for o in obs})
            notes.append(f"eval head {','.join(ev)}; eval->retired ms {[o.get('race_ms', {}).get('eval_to_retired') for o in obs]}; "
                         f"eval->forward seen ms {[o.get('race_ms', {}).get('eval_to_outcome_seen') for o in obs]}")
        if case == "restart-mid-check":
            notes.append(f"worker A: {sorted({o['extra'].get('status_after_a') for o in obs})}, KMS hits {sorted({o['extra'].get('worker_a_kms_hits') for o in obs})}")
        report.append({"version": version, "case": case, "runs": len(obs), "conforms": ok, "observations": obs})
        md.append(f"| {version} | {case} | {len(obs)} | {obs[0]['expected']} | {'/'.join(sorted({o['observed'] for o in obs}))} | "
                  f"{','.join(sorted({o['kms_hits'] for o in obs}))} | {','.join(sorted({o['attempts'] for o in obs}))} | "
                  f"{','.join(map(str, heads)) or '-'} | {','.join(retire)} | {'; '.join(notes) or '-'} | {'yes' if ok else '**NO**'} |")
    pathlib.Path(out_json).write_text(json.dumps(report, indent=1), encoding="utf-8")
    pathlib.Path(out_md).write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{sum(r['conforms'] for r in report)}/{len(report)} cases conform")


if __name__ == "__main__":
    main()
