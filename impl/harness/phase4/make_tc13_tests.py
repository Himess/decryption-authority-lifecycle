def main():
    root = pathlib.Path(sys.argv[1])
    for ver, section, calls in (("main", MAIN, 2), ("v0.13.8", V0138, 1)):
        src = root / f"results/level0/harness/{ver}/crates/kms-worker/tests/acl_retirement_real_chain.rs"
        text = src.read_text(encoding="utf-8")
        assert text.count(OLD_CALL) == calls, (ver, text.count(OLD_CALL))
        text = text.replace(OLD_CALL, NEW_CALL)
        lines = text.splitlines(keepends=True)
        first_item = next(i for i, line in enumerate(lines) if not line.startswith("//!"))
        text = HEADER + "".join(lines[:first_item]) + ALLOW + "".join(lines[first_item:]) + COMMON + section
        out = root / f"results/phase4/harness/{ver}/crates/kms-worker/tests/acl_tc13_faults.rs"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
