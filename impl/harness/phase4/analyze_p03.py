"""P0.3 analysis: stored results (V6, H7) and H4 across a restart, from the raw runs.

Usage: python -I analyze_p03.py <results/phase4 dir>
Reads raw/p03/runs/p03-main-r*/test.log (unmodified connector), raw/p03/runs/p03-main-l1-r*/test.log (Level 1),
raw/p03/logs/relayer-p03.log (relayer, three integration runs), and the host-chain recordings. Writes
p03/P03_TABLE.md and p03/P03_TABLE.json. Every cell must agree across the runs of its tree; a disagreement is listed.
"""
import collections
import glob
import json
import os
import re
import sys

KV = re.compile(r"(\w+)=(\S+)")
STEPS = ["first-request", "same-request-live", "same-request-after-retirement", "equivalent-request-after-retirement",
         "same-request-again"]


def kv(line):
    return dict(KV.findall(line))


def runs(root, pattern):
    out = []
    for d in sorted(glob.glob(os.path.join(root, "raw", "p03", "runs", pattern))):
        with open(os.path.join(d, "test.log"), encoding="utf-8") as f:
            text = f.read()
        host = 0
        with open(os.path.join(d, "host_rpc.jsonl"), encoding="utf-8") as f:
            host = sum(1 for _ in f)
        out.append((os.path.basename(d), text, host))
    return out


def main():
    root = sys.argv[1]
    result = {"connector": {}, "h4": [], "relayer": {}, "disagreements": [], "summaries": []}
    for tree, pattern in (("unmodified", "p03-main-r*"), ("level1", "p03-main-l1-r*")):
        cells = collections.defaultdict(list)
        for name, text, host in runs(root, pattern):
            for line in text.splitlines():
                if "P03-RESULT" in line:
                    d = kv(line[line.index("P03-RESULT"):])
                    cells[d["step"]].append(
                        {"run": name, "http": d["http_status"], "code": d["error_code"], "kms": d["kms_mock_hits_delta"],
                         "row": d["request_row"], "expected": f"{d['expected_status']}/{d['expected_code']}"})
                if "P03-H4" in line:
                    d = kv(line[line.index("P03-H4"):])
                    result["h4"].append({"run": d["run"], "variant": d["variant"], "worker_a": int(d["erc1271_calls_worker_a"]),
                                         "worker_b": int(d["erc1271_calls_worker_b"]), "total": int(d["total"]),
                                         "max": int(d["max_erc1271_attempts"]), "final_status": d["final_status"]})
                if "P03-SUMMARY" in line:
                    result["summaries"].append(line[line.index("P03-SUMMARY"):].strip())
            result.setdefault("host_calls", {}).setdefault(tree, []).append({"run": name, "host_rpc_records": host})
        result["connector"][tree] = {}
        for step in STEPS:
            vals = cells.get(step, [])
            if not vals:
                continue
            sig = {(v["http"], v["code"], v["kms"] != "0", v["row"]) for v in vals}
            if len(sig) != 1:
                result["disagreements"].append(f"{tree} {step}: {sorted(sig)}")
            v = vals[0]
            matches = all(f"{x['http']}/{x['code']}" == x["expected"] for x in vals)
            result["connector"][tree][step] = {"runs": len(vals), "http": v["http"], "code": v["code"],
                                               "kms_hits": sorted({x["kms"] for x in vals}), "row": v["row"],
                                               "matches_expectation": matches}
    rel = collections.defaultdict(list)
    with open(os.path.join(root, "raw", "p03", "logs", "relayer-p03.log"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("H7-RESULT"):
                d = kv(line)
                rel[(d["variant"], d["step"])].append((d["status"], d["error"], d["shares"], d["job_same"]))
    for (variant, step), vals in sorted(rel.items()):
        if len(set(vals)) != 1:
            result["disagreements"].append(f"relayer {variant} {step}: {sorted(set(vals))}")
        s, e, sh, js = vals[0]
        result["relayer"].setdefault(variant, {})[step] = {"runs": len(vals), "status": s, "error": e, "shares": sh,
                                                           "same_job": js}
    os.makedirs(os.path.join(root, "p03"), exist_ok=True)
    with open(os.path.join(root, "p03", "P03_TABLE.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(result, f, indent=1)

    md = ["# P0.3 table (generated by impl/harness/phase4/analyze_p03.py from raw/p03)", "",
          "## Connector: the same request, and an equivalent one, around a retirement", "",
          "Status / error code / KMS mock hits, per step. Unmodified: runs r1-r3; Level 1 with H7: runs r4-r6.", "",
          "| Step | Unmodified | Level 1, H7 |", "|---|---|---|"]
    for step in STEPS:
        row = [step]
        for tree in ("unmodified", "level1"):
            c = result["connector"].get(tree, {}).get(step)
            row.append("—" if not c else f"{c['http']} / {c['code']} / {','.join(c['kms_hits'])} ({c['runs']} runs"
                       f"{', as expected' if c['matches_expectation'] else ', NOT as expected'})")
        md.append("| " + " | ".join(row) + " |")
    md += ["", "## H4 across a worker restart (Level 1)", "",
           "| Run | Attempt state | ERC-1271 calls, worker A | worker B (after the restart) | Total | Limit |",
           "|---|---|---|---|---|---|"]
    for h in result["h4"]:
        md.append(f"| {h['run']} | {h['variant']} | {h['worker_a']} | {h['worker_b']} | {h['total']} | {h['max']} |")
    md += ["", "## Relayer (three integration runs)", "", "| Variant | Step | Status | Error | Shares | Same job |",
           "|---|---|---|---|---|---|"]
    for variant, steps in result["relayer"].items():
        for step, c in steps.items():
            md.append(f"| {variant} | {step} | {c['status']} | {c['error']} | {c['shares']} | {c['same_job']} "
                      f"({c['runs']} runs) |")
    md += ["", f"Disagreements across runs: {len(result['disagreements'])}"] + [f"- {d}" for d in result["disagreements"]]
    md += ["", "Summaries:"] + [f"- `{s}`" for s in result["summaries"]]
    with open(os.path.join(root, "p03", "P03_TABLE.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
