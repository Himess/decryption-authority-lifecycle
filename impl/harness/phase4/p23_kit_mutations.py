"""P2.3 negative control: the conformance kit, run against Zama main's lifecycle ACL with one gate removed at a time,
must fail. Usage: python -I p23_kit_mutations.py <impl/wt-l2-main/host-contracts> <forge> <output dir>

Each mutation replaces one exact text of contracts/ACL.sol (it must occur once), runs only the kit
(`forge test --match-path test/conformance/*`, FOUNDRY_ISOLATE=false as Zama's suites need), records the summary and
restores the file byte for byte (SHA-256 checked). Writes <output dir>/KIT_MUTATIONS.md and one log per mutation.
"""
import hashlib
import os
import re
import subprocess
import sys

MUTATIONS = [
    ("K1", "use view: isAllowed ignores retirement",
     "if (msg.sender != FHEVM_EXECUTOR_ADDRESS && _retired().retired[account]) {", "if (false) {"),
    ("K2", "use view, persistent form: persistAllowed ignores retirement",
     "return $.persistedAllowedPairs[handle][account] && !_retired().retired[account];",
     "return $.persistedAllowedPairs[handle][account];"),
    ("K3", "R7: delegateForUserDecryption without the delegator gate",
     "    ) public virtual whenNotPaused {\n        if (_retired().retired[msg.sender]) {\n            revert SenderRetired(msg.sender);\n        }\n        ACLStorage storage $ = _getACLStorage();\n        UserDecryptionDelegation storage userDecryptionDelegation",
     "    ) public virtual whenNotPaused {\n        ACLStorage storage $ = _getACLStorage();\n        UserDecryptionDelegation storage userDecryptionDelegation"),
    ("K4", "R10: no engine exemption (the executor's operand check is gated too)",
     "if (msg.sender != FHEVM_EXECUTOR_ADDRESS && _retired().retired[account]) {", "if (_retired().retired[account]) {"),
    ("K5", "handle-level on-behalf view ignores a retired delegate or contract",
     "        bytes32 handle\n    ) public view virtual returns (bool) {\n        ACLRetirementStorage storage $r = _retired();\n"
     "        if ($r.retired[delegate] || $r.retired[contractAddress]) {",
     "        bytes32 handle\n    ) public view virtual returns (bool) {\n        ACLRetirementStorage storage $r = _retired();\n"
     "        if (false) {"),
    ("K6", "handle-level on-behalf view ignores a retired delegator (no successor rule)",
     "!$.persistedAllowedPairs[handle][contractAddress]) {\n            return false;\n        }\n"
     "        if ($r.retired[delegator]) {\n            return _isConfirmedSuccessor($r, delegator, delegate);\n        }",
     "!$.persistedAllowedPairs[handle][contractAddress]) {\n            return false;\n        }\n"
     "        if (false) {\n            return _isConfirmedSuccessor($r, delegator, delegate);\n        }"),
]
SUMMARY = re.compile(r"(\d+) tests passed, (\d+) failed, (\d+) skipped")


def sha(b):
    return hashlib.sha256(b).hexdigest()


def main():
    root, forge, out = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(out, exist_ok=True)
    path = os.path.join(root, "contracts", "ACL.sol")
    rows = []
    for mid, what, old, new in MUTATIONS:
        with open(path, "rb") as f:
            original = f.read()
        text = original.decode("utf-8")
        newline = "\r\n" if "\r\n" in text else "\n"
        old_n, new_n = old.replace("\n", newline), new.replace("\n", newline)
        if text.count(old_n) != 1:
            rows.append((mid, what, f"NOT APPLIED ({text.count(old_n)} matches)", "-", ""))
            continue
        env = dict(os.environ, FOUNDRY_ISOLATE="false")
        try:
            with open(path, "wb") as f:
                f.write(text.replace(old_n, new_n).encode("utf-8"))
            proc = subprocess.run([forge, "test", "--match-path", "test/conformance/*"], cwd=root, env=env,
                                  capture_output=True, text=True, encoding="utf-8", errors="replace")
            log = proc.stdout + proc.stderr
        finally:
            with open(path, "wb") as f:
                f.write(original)
        with open(path, "rb") as f:
            assert sha(f.read()) == sha(original), "ACL.sol was not restored"
        with open(os.path.join(out, f"{mid}.log"), "w", encoding="utf-8", newline="\n") as f:
            f.write(log)
        m = SUMMARY.search(log)
        if "Compiler run failed" in log or not m:
            rows.append((mid, what, "DID NOT COMPILE", "-", ""))
            continue
        failing = sorted(set(re.findall(r"\[FAIL[^\n]*?\] (test_kit_\w+)\(", log)))
        rows.append((mid, what, "caught" if int(m.group(2)) else "NOT CAUGHT",
                     f"{m.group(1)}/{m.group(2)}/{m.group(3)}", ", ".join(failing)))
        print(mid, rows[-1][2], rows[-1][3], flush=True)
    md = ["# P2.3 kit negative control (generated by impl/harness/phase4/p23_kit_mutations.py)", "",
          "Zama main's lifecycle ACL (`impl/wt-l2-main`, branch `lifecycle/level3`) with one gate removed at a time; "
          "the kit's adapter run each time; the file restored (SHA-256 checked).", "",
          "| Id | Mutation | Outcome | Passed/failed/skipped | Failing kit tests |", "|---|---|---|---|---|"]
    md += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |" for r in rows]
    md += ["", f"Caught: {sum(1 for r in rows if r[2] == 'caught')} of {len(rows)}."]
    with open(os.path.join(out, "KIT_MUTATIONS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    print(md[-1])


if __name__ == "__main__":
    main()
