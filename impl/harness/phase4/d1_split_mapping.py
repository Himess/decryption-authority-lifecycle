"""D1: the mapping of every rule, test case and constant of the Phase 3 ERC draft to its place after the split.

Usage: python -I d1_split_mapping.py <phase3 draft> <phase4 pre-split draft> <new ERC> <companion> <out.md> <manual.md>

For each rule (R, V, O, S, C, K, H, Q, A) the script extracts its full text from each document and compares:
- with the Phase 3 draft: did the text change at all;
- with the Phase 4 pre-split draft: did the split change it, or an earlier Phase 4 task.
Test cases are compared by their table row, constants are located by value. The non-rule parts (sections, terms,
open questions) are mapped by hand in <manual.md>, which is appended unchanged.
"""
import re
import sys

p3_path, pre_path, erc_path, comp_path, out_path, manual_path = sys.argv[1:7]
docs = {name: open(p, encoding="utf-8").read().split("\n")
        for name, p in (("p3", p3_path), ("pre", pre_path), ("erc", erc_path), ("comp", comp_path))}
LABEL = {"erc": "ERC", "comp": "Companion"}
RULE = re.compile(r"^- \*\*((?:R|V|O|S|C|K|H|Q|A)\d+)\. ")


def rules(lines):
    found = {}
    heading = ""
    i = 0
    while i < len(lines):
        if lines[i].startswith("#"):
            heading = lines[i].lstrip("#").strip()
        m = RULE.match(lines[i])
        if m:
            body = [lines[i]]
            j = i + 1
            while j < len(lines) and (lines[j] == "" or lines[j].startswith("  ")):
                body.append(lines[j])
                j += 1
            while body and body[-1] == "":
                body.pop()
            found[m.group(1)] = (heading, " ".join(x.strip() for x in body))
            i = j
            continue
        i += 1
    return found


def key(rid):
    return (rid[0], int(rid[1:]))


R = {name: rules(lines) for name, lines in docs.items()}
md = ["# The ERC split: where every rule, test case and constant went (D1)", "",
      "Generated by `impl/harness/phase4/d1_split_mapping.py` from the Phase 3 draft "
      "(`erc/archive/ERC-XXXX-full-draft-phase3.md`), the Phase 4 draft just before the split "
      "(`erc/archive/ERC-XXXX-full-draft-phase4-presplit.md`), the new ERC "
      "(`erc/ERC-XXXX-decryption-authority-lifecycle.md`) and the companion "
      "(`docs/COMPANION_EXTENSIONS_AND_PROFILES.md`).", "",
      "**Columns.** *Phase 3 → now* compares each rule's text with the Phase 3 draft. *By the split* compares it with "
      "the pre-split draft: \"no\" means the split moved it unchanged, and any earlier difference comes from a Phase 4 "
      "task (listed in `results/phase4/STATUS.md`).", "",
      "## Rules", "", "| Rule | Phase 3 section | New place | Phase 3 → now | By the split |", "|---|---|---|---|---|"]
problems = []
for rid in sorted(R["p3"], key=key):
    where = [n for n in ("erc", "comp") if rid in R[n]]
    if len(where) != 1:
        problems.append(f"{rid} found in {where}")
        continue
    n = where[0]
    new_text = R[n][rid][1]
    changed_p3 = "unchanged" if new_text == R["p3"][rid][1] else "changed"
    by_split = "no" if new_text == R["pre"].get(rid, ("", None))[1] else "**yes**"
    md.append(f"| {rid} | {R['p3'][rid][0]} | {LABEL[n]}: {R[n][rid][0]} | {changed_p3} | {by_split} |")
md += ["", f"{len(R['p3'])} rules; each is in exactly one new document."]

# Test cases.
def tc_rows(lines):
    out = {}
    heading = ""
    for line in lines:
        if line.startswith("#"):
            heading = line.lstrip("#").strip()
        m = re.match(r"^\| (TC\d+) \| ((?:[RVOSCKHQA]\d|Scope|S1|C1|K1|H1|Q1|A1)[^|]*)\|", line)
        if m:
            out.setdefault(m.group(1), (heading, line))
    return out


T = {name: tc_rows(lines) for name, lines in docs.items()}
md += ["", "## Test cases", "", "| Test case | New place | Phase 3 → now | By the split |", "|---|---|---|---|"]
for tc in sorted(T["p3"], key=lambda t: int(t[2:])):
    where = [n for n in ("erc", "comp") if tc in T[n]]
    if len(where) != 1:
        problems.append(f"{tc} behaviour row found in {where}")
        continue
    n = where[0]
    row = T[n][tc][1]
    md.append(f"| {tc} | {LABEL[n]}: {T[n][tc][0]} | {'unchanged' if row == T['p3'][tc][1] else 'changed'} | "
              f"{'no' if row == T['pre'].get(tc, ('', None))[1] else '**yes**'} |")

# Constants.
p3_text = "\n".join(docs["p3"])
consts = sorted(set(re.findall(r"0x[0-9a-fA-F]{8,64}", p3_text)), key=lambda c: (len(c), c.lower()))
md += ["", "## Constants", "", "Every hexadecimal constant of the Phase 3 draft (8 hex digits or more), with the first "
       "line that names it there, and where it is now.", "", "| Value | In the Phase 3 draft | Now in |", "|---|---|---|"]
for c in consts:
    first = next(line for line in docs["p3"] if c in line)
    ctx = re.sub(r"\s+", " ", first.strip())[:90].replace("|", "/")
    where = [LABEL[n] for n in ("erc", "comp") if c.lower() in "\n".join(docs[n]).lower()]
    if not where:
        problems.append(f"constant {c} missing")
    md.append(f"| `{c}` | {ctx} | {', '.join(where) or '**missing**'} |")
md += ["", "## Everything else", ""]
md += open(manual_path, encoding="utf-8").read().rstrip("\n").split("\n")
md += ["", "## Check", "", "Problems found by the generator: " + ("none." if not problems else "; ".join(problems))]
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(md) + "\n")
print("rules", len(R["p3"]), "test cases", len(T["p3"]), "constants", len(consts), "problems", problems)
