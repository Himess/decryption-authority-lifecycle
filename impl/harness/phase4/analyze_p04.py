"""Builds the P0.4 connector matrix (Phase 4: the EIP-7851 gap) from the runs of run_p04.sh.

Usage: python -I analyze_p04.py <out.json> <out.md> <run_dir> [<run_dir> ...]

Each run directory holds test.log (P04-RESULT lines) and host_rpc.jsonl (the proxy's record). For every row label
(without its run id) it reports, per run: expected and observed outcome, KMS-mock hits, attempts, error code; and,
from the wire, what eth_getCode answered for the request (and whether the proxy rewrote it to 0xef0101) and each
isValidSignature call (gas, result). A row conforms when every run observed the expected outcome.
"""
import collections
import json
import pathlib
import re
import sys

RESULT = re.compile(
    r"P04-RESULT label=(?P<label>\S+) version=(?P<version>\S+) tree=(?P<tree>\S+) expected=(?P<expected>\S+) "
    r"observed=(?P<observed>\S+) kms_mock_hits=(?P<kms>\S+) error_counter=(?P<ec>\S+) error_code=(?P<code>\S+) "
    r"wall_ms=(?P<wall>\d+)"
)
ERC1271 = "0x1626ba7e"


def wire_by_label(path):
    out = collections.defaultdict(lambda: {"getCode": [], "isValidSignature": [], "calls": 0})
    for line in open(path, encoding="utf-8"):
        r = json.loads(line)
        label = r["path"].strip("/")
        w = out[label]
        w["calls"] += 1
        req = r["req"]
        resp = r.get("resp") or {}
        if req.get("method") == "eth_getCode":
            code = resp.get("result") if isinstance(resp, dict) else None
            w["getCode"].append({"code": (code or "")[:8], "rewritten": bool(r.get("rewrite"))})
        elif req.get("method") == "eth_call":
            call = req["params"][0]
            data = (call.get("input") or call.get("data") or "")
            if data[:10].lower() == ERC1271:
                res = resp.get("result") if isinstance(resp, dict) else None
                err = (resp.get("error") or {}).get("message") if isinstance(resp, dict) else None
                w["isValidSignature"].append({"gas": int(call["gas"], 16) if call.get("gas") else None,
                                              "result": (res or "")[:10] or None, "error": err})
    return out


def main():
    out_json, out_md = sys.argv[1], sys.argv[2]
    cells = collections.OrderedDict()
    runs = []
    for run_dir in map(pathlib.Path, sys.argv[3:]):
        text = (run_dir / "test.log").read_text(encoding="utf-8", errors="replace")
        wire = wire_by_label(run_dir / "host_rpc.jsonl")
        runs.append(str(run_dir.name))
        for m in RESULT.finditer(text):
            d = m.groupdict()
            parts = d["label"].split(".")  # p04.<run>.<tree>.<rest...>
            key = (d["version"], d["tree"], ".".join(parts[3:]))
            w = wire.get(d["label"], {"getCode": [], "isValidSignature": [], "calls": 0})
            cells.setdefault(key, []).append({
                "run": parts[1], "expected": d["expected"], "observed": d["observed"], "kms_hits": d["kms"],
                "attempts": d["ec"], "error_code": d["code"], "wall_ms": int(d["wall"]), "getCode": w["getCode"],
                "isValidSignature": w["isValidSignature"], "rpc_calls": w["calls"],
            })
    rows = []
    for (version, tree, row), obs in cells.items():
        conforms = all(o["observed"] == o["expected"] for o in obs)
        codes = sorted({f"{g['code']}{'*' if g['rewritten'] else ''}" for o in obs for g in o["getCode"]})
        erc = sorted({f"{c['gas']}:{c['result'] or c['error']}" for o in obs for c in o["isValidSignature"]})
        rows.append({"version": version, "tree": tree, "row": row, "runs": len(obs), "expected": obs[0]["expected"],
                     "observed": sorted({o["observed"] for o in obs}), "kms_hits": sorted({o["kms_hits"] for o in obs}),
                     "attempts": sorted({o["attempts"] for o in obs}), "error_codes": sorted({o["error_code"] for o in obs}),
                     "getCode": codes, "isValidSignature": erc, "conforms": conforms, "observations": obs})
    report = {"runs": runs, "rows": rows,
              "summary": {"rows": len(rows), "conforming": sum(r["conforms"] for r in rows)}}
    md = ["# P0.4 connector matrix (generated by impl/harness/phase4/analyze_p04.py)", "",
          f"Rows conforming: {report['summary']['conforming']}/{report['summary']['rows']}. "
          "getCode: the code the worker read for the request (`*` = rewritten by the proxy to 0xef0101 ‖ delegate). "
          "isValidSignature: gas:result of each ERC-1271 call.", "",
          "| Line | Tree | Row | Runs | Expected | Observed | KMS hits | Attempts | Error code | getCode | isValidSignature | OK |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['version']} | {r['tree']} | {r['row']} | {r['runs']} | {r['expected']} | "
                  f"{'/'.join(r['observed'])} | {','.join(r['kms_hits'])} | {','.join(r['attempts'])} | "
                  f"{','.join(r['error_codes'])} | {' '.join(r['getCode']) or '-'} | {' '.join(r['isValidSignature']) or '-'} | "
                  f"{'yes' if r['conforms'] else '**NO**'} |")
    pathlib.Path(out_json).write_text(json.dumps(report, indent=1), encoding="utf-8")
    pathlib.Path(out_md).write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{report['summary']['conforming']}/{report['summary']['rows']} rows conform over {len(runs)} runs")


if __name__ == "__main__":
    main()
