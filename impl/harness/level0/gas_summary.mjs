// Summarize Level 0 gas raw outputs (results/level0/raw) into markdown tables.
// Usage: node gas_summary.mjs <raw dir> > <out.md>
import { readFileSync, existsSync } from "node:fs";
import path from "node:path";

const raw = process.argv[2];
const lines = ["main", "v0.13.8"];
const forks = ["prague", "osaka", "amsterdam"];
const out = [];
const p = (s) => out.push(s);

function parse(file) {
  const rows = new Map();
  if (!existsSync(file)) return rows;
  for (const l of readFileSync(file, "utf8").split(/\r?\n/)) {
    const i = l.indexOf("GAS|");
    if (i < 0) continue;
    const [, evm, label, base, level0, delta] = l.slice(i).split("|");
    rows.set(label, { evm, base: Number(base), level0: Number(level0), delta: Number(delta) });
  }
  return rows;
}

p(`# Level 0 gas summary (generated by impl/harness/level0/gas_summary.mjs)\n`);
for (const L of lines) {
  const envFile = path.join(raw, `L0_gas_environment_${L}.txt`);
  if (!existsSync(envFile)) continue;
  p(`Environment of the ${L} run:\n`);
  p(readFileSync(envFile, "utf8").trim().split(/\r?\n/).map((s) => `    ${s}`).join("\n"));
  p("");
}
for (const L of lines) {
  for (const runs of [800, 200]) {
    const data = Object.fromEntries(forks.map((f) => [f, parse(path.join(raw, `L0_gas_${L}_runs${runs}_${f}.log`))]));
    const labels = [...new Set(forks.flatMap((f) => [...data[f].keys()]))];
    if (!labels.length) continue;
    const baseName = L === "main" ? "v0.7.0" : "v0.4.0";
    const l0Name = L === "main" ? "v0.8.0" : "v0.4.1";
    p(`## ${L}, optimizer runs ${runs}: Foundry, baseline ACL ${baseName} vs Level 0 ACL ${l0Name}\n`);
    p(`| Measurement | ${forks.map((f) => `${f}: base / L0 / delta`).join(" | ")} |`);
    p(`|---|${forks.map(() => "---").join("|")}|`);
    for (const lab of labels) {
      const cells = forks.map((f) => {
        const r = data[f].get(lab);
        return r ? `${r.base.toLocaleString("en-US")} / ${r.level0.toLocaleString("en-US")} / ${r.delta >= 0 ? "+" : ""}${r.delta.toLocaleString("en-US")}` : "n/a";
      });
      p(`| ${lab} | ${cells.join(" | ")} |`);
    }
    p("");
  }
}

p(`## main, anvil receipts (transaction-level gasUsed), optimizer runs 800\n`);
const anv = Object.fromEntries(
  forks.map((f) => {
    const fp = path.join(raw, `L0_gas_anvil_main_${f}.json`);
    return [f, existsSync(fp) ? JSON.parse(readFileSync(fp, "utf8")) : null];
  }),
);
const keys = [
  ["calibration", "eth_transfer_no_data"],
  ["calibration", "calldata_1000_zero_bytes"],
  ["calibration", "calldata_1000_nonzero_bytes"],
  ["calibration", "sstore_new_slot"],
  ["calibration", "sstore_same_value_again"],
  ["v0_7_0", "allow_new_pair"],
  ["v0_8_0", "allow_new_pair"],
  ["v0_7_0", "allow_existing_pair"],
  ["v0_8_0", "allow_existing_pair"],
  ["v0_8_0", "retireAccount"],
  ...[1, 10, 100, 500].flatMap((n) => [
    ["v0_7_0", `carry_n${n}`],
    ["v0_8_0", `carry_n${n}`],
  ]),
];
p(`| Item | ${forks.join(" | ")} | calldata bytes |`);
p(`|---|${forks.map(() => "---").join("|")}|---|`);
for (const [g, k] of keys) {
  const cells = forks.map((f) => (anv[f]?.[g]?.[k] ? anv[f][g][k].gasUsed.toLocaleString("en-US") : "n/a"));
  const cd = anv.prague?.[g]?.[k]?.calldataBytes ?? "";
  const lab = g === "calibration" ? k : `${g === "v0_7_0" ? "v0.7.0" : "v0.8.0"} ${k}${g === "v0_8_0" && k.startsWith("carry") ? " (+ retireAccount)" : ""}`;
  p(`| ${lab} | ${cells.join(" | ")} | ${cd} |`);
}
p("");
for (const f of forks) {
  const a = anv[f];
  if (!a) continue;
  for (const v of ["v0_7_0", "v0_8_0"]) {
    const c1 = a[v].carry_n1.gasUsed;
    const c500 = a[v].carry_n500.gasUsed;
    const per = (c500 - c1) / 499;
    const cap = 16_777_216;
    const fixed = c1 - per;
    p(`- ${f} ${v}: carry per handle ${per.toFixed(1)} gas; fixed ${fixed.toFixed(0)}; max handles under the EIP-7825 cap (2^24) ${Math.floor((cap - fixed) / per)}`);
  }
}
console.log(out.join("\n"));
