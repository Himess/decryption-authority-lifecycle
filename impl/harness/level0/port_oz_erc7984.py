"""Vendor OpenZeppelin confidential-contracts 0.5.3 (ERC-7984 core) as a test-only
dependency of Zama host-contracts, which pin solc 0.8.24.

OZ 0.5.3 declares `pragma solidity ^0.8.27` only because it uses
`require(bool, CustomError(...))`, which legacy codegen supports from 0.8.27.
The port is mechanical and semantics-preserving:
  1. `pragma solidity ^0.8.27;`          -> `pragma solidity ^0.8.24;`
  2. `require(COND, ERR(ARGS));`         -> `if (!(COND)) revert ERR(ARGS);`
  3. `"@fhevm/solidity/lib/FHE.sol"`     -> `"@fhevm-host-contracts/lib/FHE.sol"`
     (host-contracts' own copy of the FHE library; identical to
     library-solidity/lib/FHE.sol on main except one FheType import path)
Every other byte is unchanged, except that a multi-line require collapses
onto one line. Inspect with: diff <oz_package_dir>/<file> <out_dir>/<file>.
Usage: python -I port_oz_erc7984.py <oz_package_dir> <out_dir>
"""
import hashlib, os, sys

FILES = [
    "interfaces/IERC7984.sol",
    "interfaces/IERC7984Receiver.sol",
    "token/ERC7984/ERC7984.sol",
    "token/ERC7984/extensions/ERC7984ObserverAccess.sol",  # Level 2, Profile A (TC23)
    "token/ERC7984/utils/ERC7984Utils.sol",
    "utils/FHESafeMath.sol",
]
FHE_OLD = '"@fhevm/solidity/lib/FHE.sol"'
FHE_NEW = '"@fhevm-host-contracts/lib/FHE.sol"'


def split_top_level(s):
    depth = 0
    for i, c in enumerate(s):
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            return s[:i], s[i + 1 :]
    raise ValueError("no top-level comma in require(...)")


def port_requires(text):
    out, i, n_req = [], 0, 0
    records = []
    while True:
        j = text.find("require(", i)
        if j < 0:
            out.append(text[i:])
            break
        out.append(text[i:j])
        k, depth = j + len("require("), 1
        while depth:
            c = text[k]
            depth += 1 if c == "(" else -1 if c == ")" else 0
            k += 1
        assert text[k] == ";", "require( not followed by ;"
        inner = text[j + len("require(") : k - 1]
        cond, err = split_top_level(inner)
        records.append((text[j : k + 1], cond, err))
        cond_s, err_s = cond.strip(), err.strip()
        out.append(f"if (!({cond_s})) revert {err_s};")
        n_req += 1
        i = k + 1
    return "".join(out), n_req, records


def main():
    src_dir, out_dir = sys.argv[1], sys.argv[2]
    for rel in FILES:
        raw = open(os.path.join(src_dir, rel), "rb").read()
        text = raw.decode("utf-8")
        new = text
        notes = []
        if "pragma solidity ^0.8.27;" in new:
            new = new.replace("pragma solidity ^0.8.27;", "pragma solidity ^0.8.24;")
            notes.append("pragma ^0.8.27 -> ^0.8.24")
        n_fhe = new.count(FHE_OLD)
        new = new.replace(FHE_OLD, FHE_NEW)
        notes.append(f"{n_fhe} FHE import(s) re-pointed to host-contracts lib/FHE.sol")
        new, n_req, _ = port_requires(new)
        if n_req:
            notes.append(f"{n_req} require(bool, error) -> if (!(cond)) revert error")
        lines = new.split("\n")
        assert lines[0].startswith("// SPDX"), rel
        header = [
            "// TEST-ONLY VENDORED COPY, generated by impl/harness/level0/port_oz_erc7984.py. Do not edit by hand.",
            f"// Source: @openzeppelin/confidential-contracts 0.5.3, {rel}",
            f"// Source sha256: {hashlib.sha256(raw).hexdigest()}",
            "// Mechanical port to solc 0.8.24 (nothing else changed): " + "; ".join(notes),
        ]
        out = "\n".join([lines[0]] + header + lines[1:])
        dst = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        open(dst, "w", encoding="utf-8", newline="\n").write(out)
        print(f"{rel}: {', '.join(notes)}")


if __name__ == "__main__":
    main()
