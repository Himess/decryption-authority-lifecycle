"""Judges a run of the Zama worker harness against the verifier conformance fixtures (TC13, TC14, TC15).

Usage: python -I conformance/verifier/check_zama_worker.py <fixture.json> <run dir or test.log> [...]
       [--out report.md] [--line main|v0.13.8]

The harness (results/{level0,level1,phase4}/harness, generated by impl/harness/{level1,phase4}/make_*_tests.py and run
by impl/harness/phase4/vps/*.sh) logs one RESULT line per request. For every fixture row this script finds the
row's line in each given run and applies the row's rule:
  not-forwarded  the request was not forwarded to the KMS (V1: a retired subject is never served);
  forwarded      it was forwarded (liveness of the harness's controls);
  any            the rule leaves the outcome open (V1 permits refusing when a view call fails);
  final-denial   refused at the first attempt, never retried and never revived (V7);
  typed-denial   refused with the given error code (V7, on a path that reports codes);
  served / not-served  the connector's HTTP status for a stored result (V6).
A row is `conforms`, `violates` or `missing` (no line for it in that run). Violations describe the verifier under
test; the script exits 0 unless a row is missing from every run.
"""
import glob
import json
import os
import re
import sys

KV = re.compile(r"(\w+)=(\S+)")


def lines_of(path):
    files = [path] if os.path.isfile(path) else glob.glob(os.path.join(path, "test.log"))
    for f in files:
        with open(f, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                yield line


def parse(run, kind):
    out = []
    for line in lines_of(run):
        i = line.find(kind + " ")
        if i >= 0:
            out.append(dict(KV.findall(line[i:])))
    return out


def find(row, results):
    h = row["harness"]
    for r in results:
        if h["result_line"] == "TC13-RESULT":
            if (r.get("version") == row["line"] and r.get("path") == h["path"] and r.get("subject") == h["subject"]
                    and r.get("view") == h["view"] and r.get("fault") == h["fault"]):
                return r
        elif h["result_line"] == "P02-RESULT":
            if r.get("version") == row["line"] and r.get("case") == h["case"]:
                return r
        elif h["result_line"] == "L0-RESULT":
            if r.get("label") == h["label"]:
                return r
        elif h["result_line"] == "P03-RESULT":
            if r.get("version") == row["line"] and r.get("tree") == h["tree"] and r.get("step") == h["step"]:
                return r
    return None


def judge(row, r):
    e = row["expect"]
    if e == "any":
        return True
    if e in ("not-forwarded", "forwarded"):
        forwarded = r.get("observed") == "Forwarded"
        return forwarded == (e == "forwarded")
    if e == "final-denial":
        return r.get("observed") == "Rejected" and r.get("error_counter") in ("1",) and r.get("kms_mock_hits") == "0"
    if e == "typed-denial":
        return r.get("observed") == "Rejected" and r.get("error_code") == row.get("expect_code")
    if e == "served":
        return r.get("http_status") == "200"
    if e == "not-served":
        return r.get("http_status") != "200" and r.get("kms_mock_hits_delta") == "0"
    raise ValueError(f"unknown expectation {e}")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else None
    only = sys.argv[sys.argv.index("--line") + 1] if "--line" in sys.argv else None
    args = [a for a in args if a not in (out, only)]
    fixture = json.load(open(args[0], encoding="utf-8"))
    if only:
        fixture["rows"] = [row for row in fixture["rows"] if row["line"] == only]
    runs = args[1:]
    kinds = {row["harness"]["result_line"] for row in fixture["rows"]}
    per_run = {run: {k: parse(run, k) for k in kinds} for run in runs}
    lines = [f"# {fixture['fixture']} against the Zama worker harness", "",
             f"Fixture: `{os.path.basename(args[0])}` ({len(fixture['rows'])} rows). Runs: {len(runs)}.", "",
             "| Row | Rule | Expect | " + " | ".join(os.path.basename(os.path.normpath(r)) for r in runs) + " |",
             "|---|---|---|" + "---|" * len(runs)]
    totals = {"conforms": 0, "violates": 0, "missing": 0}
    missing_everywhere = 0
    for row in fixture["rows"]:
        cells, seen = [], False
        for run in runs:
            r = find(row, per_run[run][row["harness"]["result_line"]])
            if r is None:
                cells.append("missing")
                totals["missing"] += 1
                continue
            seen = True
            ok = judge(row, r)
            totals["conforms" if ok else "violates"] += 1
            cells.append("conforms" if ok else f"**violates** ({r.get('observed', r.get('http_status'))})")
        if not seen:
            missing_everywhere += 1
        lines.append(f"| `{row['id']}` | {row['rule']} | {row['expect']} | " + " | ".join(cells) + " |")
    lines += ["", f"Cells: {totals['conforms']} conform, {totals['violates']} violate, {totals['missing']} missing. "
                  f"Rows missing from every run: {missing_everywhere}."]
    text = "\n".join(lines) + "\n"
    if out:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(text if not out else lines[-1])
    sys.exit(1 if missing_everywhere else 0)


if __name__ == "__main__":
    main()
